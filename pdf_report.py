"""
pdf_report.py
--------------
Generates a downloadable PDF summary of a single credit risk prediction,
using fpdf2 (pure-Python, no system dependencies).
"""

from datetime import datetime
from fpdf import FPDF

NAVY = (11, 31, 58)
BLUE = (37, 99, 235)
GREEN = (21, 128, 61)
RED = (185, 28, 28)
MUTED = (91, 107, 140)


class ReportPDF(FPDF):
    def header(self):
        self.set_fill_color(*NAVY)
        self.rect(0, 0, 210, 22, "F")
        self.set_xy(10, 6)
        self.set_text_color(255, 255, 255)
        self.set_font("Helvetica", "B", 16)
        self.cell(0, 10, "CreditSense AI - Risk Assessment Report", ln=1)
        self.set_text_color(0, 0, 0)
        self.ln(10)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(*MUTED)
        self.cell(0, 10, f"Generated {datetime.now().strftime('%Y-%m-%d %H:%M')} | "
                          f"Academic project - not a real lending decision", align="C")


def build_prediction_report(result: dict, applicant_inputs: dict, explanation: list) -> bytes:
    """Builds a one-page PDF report for a single prediction.

    Args:
        result: dict with keys risk, probability, message, applicant_name
        applicant_inputs: the raw form data submitted by the user
        explanation: list of {"feature","impact","direction"} dicts

    Returns:
        PDF file content as bytes.
    """
    pdf = ReportPDF()
    pdf.add_page()
    pdf.set_auto_page_break(auto=True, margin=20)

    is_low_risk = result.get("risk") == "Low Risk"
    color = GREEN if is_low_risk else RED

    # ---- Applicant + verdict summary ----
    pdf.set_font("Helvetica", "B", 13)
    pdf.set_text_color(*NAVY)
    pdf.cell(0, 8, f"Applicant: {result.get('applicant_name', 'N/A')}", ln=1)

    pdf.set_font("Helvetica", "B", 22)
    pdf.set_text_color(*color)
    pdf.cell(0, 12, result.get("risk", "N/A"), ln=1)

    pdf.set_font("Helvetica", "", 11)
    pdf.set_text_color(30, 30, 30)
    pdf.cell(0, 7, f"Confidence: {result.get('probability', 'N/A')}%", ln=1)
    pdf.cell(0, 7, f"Recommendation: {result.get('message', 'N/A')}", ln=1)

    cibil_val = applicant_inputs.get("cibil_score")
    if cibil_val is not None:
        pdf.set_font("Helvetica", "B", 11)
        pdf.set_text_color(*BLUE)
        pdf.cell(0, 7, f"CIBIL Score: {cibil_val}", ln=1)
        pdf.set_text_color(30, 30, 30)

    pdf.ln(4)

    # ---- Applicant details table ----
    pdf.set_font("Helvetica", "B", 12)
    pdf.set_text_color(*NAVY)
    pdf.cell(0, 8, "Applicant Details", ln=1)
    pdf.set_draw_color(220, 220, 220)
    pdf.line(10, pdf.get_y(), 200, pdf.get_y())
    pdf.ln(3)

    labels = {
        "age": "Age", "gender": "Gender", "employment_status": "Employment Status",
        "annual_income": "Annual Income", "loan_amount": "Loan Amount",
        "loan_duration": "Loan Duration (months)", "credit_history": "Credit History",
        "existing_loans": "Existing Loans", "debt_to_income_ratio": "Debt-to-Income Ratio (%)",
        "loan_purpose": "Loan Purpose", "cibil_score": "CIBIL Score",
        "pan_verified": "PAN / KYC Verified", "collateral_provided": "Collateral Provided",
        "co_applicant_income": "Co-Applicant Income", "bank_relationship_years": "Bank Relationship (Years)",
        "residential_status": "Residential Status",
    }
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(40, 40, 40)
    for key, label in labels.items():
        if key in applicant_inputs:
            pdf.set_font("Helvetica", "B", 10)
            pdf.cell(60, 6.5, label + ":", border=0)
            pdf.set_font("Helvetica", "", 10)
            pdf.cell(0, 6.5, str(applicant_inputs[key]), ln=1)
    pdf.ln(4)

    # ---- Explanation ----
    if explanation:
        pdf.set_font("Helvetica", "B", 12)
        pdf.set_text_color(*NAVY)
        pdf.cell(0, 8, "Top Factors Behind This Prediction", ln=1)
        pdf.line(10, pdf.get_y(), 200, pdf.get_y())
        pdf.ln(3)

        pdf.set_font("Helvetica", "", 10)
        for item in explanation:
            verb = "increased" if item["direction"] == "supports" else "decreased"
            pdf.set_text_color(*(GREEN if item["direction"] == "supports" else RED))
            pdf.set_font("Helvetica", "B", 10)
            pdf.cell(70, 6.5, item["feature"], border=0)
            pdf.set_font("Helvetica", "", 10)
            pdf.set_text_color(40, 40, 40)
            pdf.cell(0, 6.5, f"{verb} confidence in this verdict by ~{abs(item['impact'])} pts", ln=1)
        pdf.ln(4)

    # ---- Disclaimer ----
    pdf.set_font("Helvetica", "I", 8.5)
    pdf.set_text_color(*MUTED)
    pdf.multi_cell(0, 5, "Disclaimer: CreditSense AI is a student / academic project. This prediction "
                          "was generated by a machine learning model trained on synthetic data and must "
                          "not be used for real lending or credit decisions.")

    return bytes(pdf.output())
